def gid(c):
    return 'g'+format(ord(c),'x')

def glyph_path(rows):
    cmds=[]
    for y,row in enumerate(rows):
        run=False; start=0
        for x,v in enumerate(row+'0'):
            if v=='1' and not run:
                run=True; start=x
            elif v=='0' and run:
                cmds.append(f'M{start} {y}h{x-start}v1H{start}z')
                run=False
    return ''.join(cmds)

def text_group(text, cx, y, scale, color, anchor='middle', tracking=1.0):
    widths=[]
    total=0
    for c in text:
        if c==' ':
            w=5.0
        else:
            w=len(FONT[c][0])+tracking
        widths.append((c,w)); total+=w
    total-=tracking if text else 0
    if anchor=='middle': x0=cx-total*scale/2
    elif anchor=='end': x0=cx-total*scale
    else: x0=cx
    out=[f'<g transform="translate({x0:.2f} {y:.2f}) scale({scale:.3f})" fill="{color}">']
    x=0
    for c,w in widths:
        if c!=' ':
            out.append(f'<use href="#{gid(c)}" x="{x:.2f}"/>')
        x+=w
    out.append('</g>')
    return ''.join(out)

